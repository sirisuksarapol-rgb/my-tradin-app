import bcrypt
import jwt
import os
from datetime import datetime, timedelta
from dotenv import load_dotenv

# โหลดตัวแปรสภาพแวดล้อม (Environment Variables) จากไฟล์ .env
load_dotenv()
JWT_SECRET = os.getenv("JWT_SECRET")


# =========================================================================
# 1. ฟังก์ชันเข้ารหัสรหัสผ่าน (Hash Password)
# =========================================================================
def hash_password(password):
    """
    ฟังก์ชันสำหรับแปลงรหัสผ่านแบบข้อความธรรมดา (Plain text) ให้กลายเป็นรหัสผ่านที่ปลอดภัยด้วยการ Hash
    
    รายละเอียดการทำงาน:
    * รับค่า password แบบข้อความธรรมดา.
    * แปลงรหัสผ่านเป็นไบต์และทำการสร้าง salt ด้วย bcrypt.gensalt().
    * เข้ารหัสรหัสผ่านด้วย bcrypt.hashpw และแปลงผลลัพธ์กลับเป็นสตริงเพื่อบันทึกลงฐานข้อมูล.
    """
    return bcrypt.hashpw(password.encode(), bcrypt.gensalt()).decode()


# =========================================================================
# 2. ฟังก์ชันตรวจสอบรหัสผ่าน (Check Password)
# =========================================================================
def check_password(password, hashed):
    """
    ฟังก์ชันสำหรับตรวจสอบความถูกต้องของรหัสผ่านที่ผู้ใช้กรอกเทียบกับรหัสผ่านที่เข้ารหัสไว้ในฐานข้อมูล
    
    รายละเอียดการทำงาน:
    * รับค่า password (รหัสผ่านที่ผู้ใช้กรอก) และ hashed (รหัสผ่านที่เข้ารหัสแล้วในระบบ).
    * แปลงทั้งสองค่าเป็นไบต์และตรวจสอบความถูกต้องด้วย bcrypt.checkpw.
    * คืนค่า True หากรหัสผ่านถูกต้อง หรือ False หากรหัสผ่านไม่ถูกต้อง.
    """
    return bcrypt.checkpw(password.encode(), hashed.encode())


# =========================================================================
# 3. ฟังก์ชันสร้าง JSON Web Token (Generate Token)
# =========================================================================
def generate_token(member_id):
    """
    ฟังก์ชันสำหรับสร้าง JWT Token เพื่อใช้ในการยืนยันตัวตนของผู้ใช้งานหลังจากเข้าสู่ระบบสำเร็จ
    
    รายละเอียดการทำงาน:
    * กำหนดข้อมูล Payload ซึ่งประกอบด้วยรหัสสมาชิก (member_id) และเวลาหมดอายุ (exp) ในอีก 1 วันข้างหน้า.
    * เข้ารหัส Payload ด้วยฟังก์ชัน jwt.encode โดยใช้กุญแจลับ JWT_SECRET และอัลกอริทึม HS256.
    * คืนค่า Token ที่สร้างเสร็จแล้วในรูปแบบสตริง.
    """
    payload = {
        "member_id": member_id,
        "exp": datetime.utcnow() + timedelta(days=1)
    }
    return jwt.encode(payload, JWT_SECRET, algorithm="HS256")


# =========================================================================
# 4. ฟังก์ชันตรวจสอบและถอดรหัส Token (Verify Token)
# =========================================================================
def verify_token(token):
    """
    ฟังก์ชันสำหรับตรวจสอบความถูกต้องและถอดรหัส JWT Token ที่ส่งมาจากฝั่งไคลเอนต์
    
    รายละเอียดการทำงาน:
    * รับค่า token ที่ต้องการตรวจสอบ.
    * ทำการถอดรหัสด้วย jwt.decode โดยใช้กุญแจลับ JWT_SECRET และอัลกอริทึม HS256.
    * คืนค่าข้อมูลภายใน Payload (เช่น member_id) หาก Token ถูกต้องและยังไม่หมดอายุ.
    """
    return jwt.decode(token, JWT_SECRET, algorithms=["HS256"])